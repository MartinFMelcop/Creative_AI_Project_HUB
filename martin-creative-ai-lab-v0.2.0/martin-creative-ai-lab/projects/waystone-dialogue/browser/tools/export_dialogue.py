#!/usr/bin/env python3
"""Export preserved dialogue data; Python remains the adaptation's source."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scene import ACTIONS, INTRO, VARIANTS, SCENE_VARIANTS

data = {"intro": INTRO, "actions": ACTIONS, "variants": [
    {key: getattr(v, key) for key in ("source_id", "action", "priority", "text",
      "stress", "trust", "respect", "mood", "flags", "events")}
    for v in VARIANTS + SCENE_VARIANTS]}
output = "// Generated by tools/export_dialogue.py from the preserved Python scene.\n"
output += "export const DIALOGUE = " + json.dumps(data, indent=2) + ";\n"
target = ROOT / "browser/dist/dialogue.js"
if "--check" in sys.argv:
    if target.read_text() != output:
        raise SystemExit("Dialogue data differs; run tools/export_dialogue.py")
    print("Dialogue source export matches")
else:
    target.write_text(output)
